-- Logical schema v1. Keep in step with ../postgres and ../oracle (same file
-- names, same tables and columns); docs/DATABASE.md has the portability rules.

CREATE TABLE spl_runs (
    id             TEXT PRIMARY KEY,   -- UUIDv7, generated by the app
    op_id          TEXT NOT NULL,
    status         TEXT NOT NULL,      -- queued | running | succeeded | failed | cancelled
    input_json     TEXT NOT NULL,
    output_json    TEXT,
    error_message  TEXT,
    host_name      TEXT,
    git_sha        TEXT,
    env_json       TEXT,               -- GPU, driver, CUDA and app versions
    created_at_ms  INTEGER NOT NULL,   -- Unix epoch milliseconds, UTC
    started_at_ms  INTEGER,
    finished_at_ms INTEGER
);
CREATE INDEX spl_runs_op_created ON spl_runs (op_id, created_at_ms);

CREATE TABLE spl_artifacts (
    id            TEXT PRIMARY KEY,    -- blake3 hex of the bytes
    kind          TEXT NOT NULL,
    media_type    TEXT NOT NULL,
    size_bytes    INTEGER NOT NULL,
    uri           TEXT NOT NULL,
    meta_json     TEXT,
    created_at_ms INTEGER NOT NULL
);

CREATE TABLE spl_run_artifacts (
    run_id      TEXT NOT NULL REFERENCES spl_runs (id),
    artifact_id TEXT NOT NULL REFERENCES spl_artifacts (id),
    direction   TEXT NOT NULL,         -- input | output
    slot_name   TEXT NOT NULL,
    PRIMARY KEY (run_id, direction, slot_name)
);

CREATE TABLE spl_metrics (
    run_id       TEXT NOT NULL REFERENCES spl_runs (id),
    seq          INTEGER NOT NULL,
    metric_key   TEXT NOT NULL,
    metric_value REAL NOT NULL,
    unit         TEXT,                 -- NULL when unitless (Oracle stores '' as NULL)
    PRIMARY KEY (run_id, seq)
);
